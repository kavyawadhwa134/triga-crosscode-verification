#!/usr/bin/env python3
"""Convert OpenMC 2-group MGXS to a GeN-Foam nuclearData dictionary.

Needs only h5py + numpy (not OpenMC), so it runs on a machine that has
GeN-Foam but no OpenMC installation.

Usage:
    python3 genfoam/tools/openmc2genfoam.py genfoam/lattice/mgxs_2g_data.h5 \
        genfoam/triga_steady/constant/neutroRegion/nuclearData

Physics mapping (diffusion model, see
applications/modules/neutronics/diffusion/include/):
  - removal_g = absorption_g + sum_{g' != g} S_{g -> g'}   (out-scatter
    to other groups only; in-scatter is added explicitly by
    calcScatteringSource, within-group scatter cancels)
  - nuSigmaEff = nu-fission XS
  - sigmaPow   = kappa-fission XS (power density = flux * sigmaPow)
  - scatteringMatrixP0[g_from][g_to] = S matrix (P0)
  - chiPrompt  = fission spectrum chi; chiDelayed = (1 0) (delayed
    neutrons born fast)
  - D, IV converted to SI; macroscopic XS converted 1/cm -> 1/m
  - discFactor = 1 (no heterogeneous discontinuity data at this stage)
  - lambda/Beta = U-235 Keepin 6-group (TRIGA fuel is U-235 driven;
    computed effective values are a refinement for later)
  - integralFlux = 1 (initial guess / normalization)

Input HDF5 (written by genfoam/lattice/extract_mgxs.py): datasets total[G],
absorption[G], fission[G], nu_fission[G], kappa_fission[G],
scatter[G_in, G_out], chi[G], inv_velocity[G] (s/cm), diffcoef[G] (cm),
group_edges_eV[G+1]; attrs keff, keff_std. Group 0 = fast.
"""
import sys
import h5py
import numpy as np

EV_TO_J = 1.602176634e-19

# U-235 thermal 6-group delayed data (Keepin): decay constants [1/s],
# yields (sum = 0.0065). Used because TRIGA fissions are U-235 dominated.
LAMBDA = [0.0124, 0.0305, 0.111, 0.301, 1.14, 3.01]
BETA = [0.000215, 0.001424, 0.001274, 0.002568, 0.000748, 0.000273]


def fmt(vals):
    return '(' + ' '.join(f'{v:.6g}' for v in vals) + ')'


def main(inp, outp):
    with h5py.File(inp, 'r') as f:
        G = len(f['absorption'])
        assert G == 2, f'converter currently supports 2 groups, got {G}'
        absorption = f['absorption'][:]
        nuf = f['nu_fission'][:]
        kappa = f['kappa_fission'][:]
        scat = f['scatter'][:, :]
        chi = f['chi'][:]
        invv = f['inv_velocity'][:]      # s/cm
        diffc = f['diffcoef'][:]         # cm
        edges = f['group_edges_eV'][:]
        keff = float(f.attrs['keff'])
        keff_std = float(f.attrs['keff_std'])

    removal = absorption + (scat.sum(axis=1) - np.diag(scat))

    # SI conversions
    removal_si = removal * 100.0          # 1/cm -> 1/m
    nuf_si = nuf * 100.0
    pow_si = kappa * EV_TO_J * 100.0      # eV/cm -> J/m
    scat_si = scat * 100.0
    diff_si = diffc * 0.01                # cm -> m
    iv_si = invv * 100.0                  # s/cm -> s/m

    header = f"""/*--------------------------------*- C++ -*----------------------------------*
|    TRIGA Mark I 2-group nuclearData — generated by tools/openmc2genfoam.py
|    Source: {inp} (pin-cell homogenized, ENDF/B-VIII.0)
|    k-inf = {keff:.5f} +/- {keff_std:.5f}; group boundary 0.625 eV
*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       dictionary;
    object      nuclearData;
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

energyGroups    {G};

precGroups      {len(LAMBDA)};


xsVariables
{{}}

states
(
    reference
    {{
        zones
        (
            zone0
            {{
                fuelFraction    1;
                sigmaRemoval    nonuniform List<scalar> {G}{fmt(removal_si)};
                nuSigmaEff      nonuniform List<scalar> {G}{fmt(nuf_si)};
                sigmaPow        nonuniform List<scalar> {G}{fmt(pow_si)};
                scatteringMatrixP0 {G} {G} (
                    ( {scat_si[0, 0]:.6g} {scat_si[0, 1]:.6g} )
                    ( {scat_si[1, 0]:.6g} {scat_si[1, 1]:.6g} )
                );
                discFactor      nonuniform List<scalar> {G}{fmt([1.0] * G)};
                chiPrompt       nonuniform List<scalar> {G}{fmt(chi)};
                chiDelayed      nonuniform List<scalar> {G}{fmt([1.0] + [0.0] * (G - 1))};
                IV              nonuniform List<scalar> {G}{fmt(iv_si)};
                lambda          nonuniform List<scalar> {len(LAMBDA)}{fmt(LAMBDA)};
                Beta            nonuniform List<scalar> {len(BETA)}{fmt(BETA)};
                D               nonuniform List<scalar> {G}{fmt(diff_si)};
                integralFlux    nonuniform List<scalar> {G}{fmt([1.0] * G)};
            }}
        );
    }}
);


// ************************************************************************* //
"""
    with open(outp, 'w') as fh:
        fh.write(header)
    print(f'k-inf {keff:.5f} +/- {keff_std:.5f}, '
          f'cutoff {edges[1]:.4g} eV -> wrote {outp}')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        sys.exit(f'usage: {sys.argv[0]} <mgxs_2g_data.h5> <nuclearData>')
    main(sys.argv[1], sys.argv[2])
